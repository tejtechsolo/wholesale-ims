"use client";
import { useActionState, useEffect, useRef, useState } from "react";
import { startEnrollment, verifyCode, type Enrollment } from "@/app/actions/mfa";

function CodeForm({ next, label }: { next: string; label: string }) {
  const [state, action, pending] = useActionState(verifyCode, undefined);
  return (
    <form action={action} className="stack">
      <input type="hidden" name="next" value={next} />
      <label>Authentication code
        <input name="code" inputMode="numeric" autoComplete="one-time-code" pattern="\d{6}" maxLength={6} required />
      </label>
      {state?.error && <p role="alert" className="error">{state.error}</p>}
      <button disabled={pending}>{pending ? "Checking…" : label}</button>
    </form>
  );
}

export function ChallengeForm({ next }: { next: string }) {
  return <CodeForm next={next} label="Verify" />;
}

export function EnrollForm({ next }: { next: string }) {
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [error, setError] = useState<string | null>(null);
  const started = useRef(false); // effects run twice in dev StrictMode: enrol exactly once
  useEffect(() => {
    if (started.current) return;
    started.current = true;
    startEnrollment().then((r) => (r.ok ? setEnrollment(r.data) : setError(r.error)));
  }, []);
  if (error) return <p role="alert" className="error">{error}</p>;
  if (!enrollment) return <p className="muted">Preparing…</p>;
  return (
    <div className="stack">
      {/* qr_code is an SVG data URI generated by Supabase Auth (allowed by img-src data:). */}
      <img src={enrollment.qr} alt="QR code for your authenticator app" width={200} height={200} />
      <p className="muted">Can't scan? Enter this key manually:</p>
      <code aria-label="Secret key" style={{ wordBreak: "break-all" }}>{enrollment.secret}</code>
      <CodeForm next={next} label="Turn on two-factor" />
    </div>
  );
}
